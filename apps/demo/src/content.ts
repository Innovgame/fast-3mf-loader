export const exampleCode = `import { Fast3MFLoader, fast3mfBuilder } from "fast-3mf-loader";
import { Scene } from "three";

const response = await fetch("/models/example.3mf");
if (!response.ok) throw new Error("Could not fetch the model");
const buffer = await response.arrayBuffer();

const data = await new Fast3MFLoader().parse(buffer, {
  onProgress: (percent) => console.log(percent),
});

const scene = new Scene();
scene.add(fast3mfBuilder(data));`;
